import '../../domain/entities/symbol_wise_position_report.dart';

class SymbolWisePositionReportModel extends SymbolWisePositionReport {
  const SymbolWisePositionReportModel({
    required String id,
    required String exchange,
    required String symbol,
    required double netQty,
    required double netMs,
    required double carryFwdQty,
    required double carryFwdMs,
    required double openQty,
    required double openMs,
    required double totalQty,
    required double totalMs,
    required double buyQty,
    required double buyMs,
    required double sellQty,
    required double sellMs,
    required double netAvgPrice,
    required double cmp,
    required double m2m,
    required double releasePL,
    required double netPL,
    required double brokerage,
    required double netPLWithBrokerage,
  }) : super(
         id: id,
         exchange: exchange,
         symbol: symbol,
         netQty: netQty,
         netMs: netMs,
         carryFwdQty: carryFwdQty,
         carryFwdMs: carryFwdMs,
         openQty: openQty,
         openMs: openMs,
         totalQty: totalQty,
         totalMs: totalMs,
         buyQty: buyQty,
         buyMs: buyMs,
         sellQty: sellQty,
         sellMs: sellMs,
         netAvgPrice: netAvgPrice,
         cmp: cmp,
         m2m: m2m,
         releasePL: releasePL,
         netPL: netPL,
         brokerage: brokerage,
         netPLWithBrokerage: netPLWithBrokerage,
       );
  factory SymbolWisePositionReportModel.fromJson(Map<String, dynamic> json) {
    return SymbolWisePositionReportModel(
      id: (json['id'] ?? '').toString(),
      exchange: json['exchange'] ?? '',
      symbol: json['symbol'] ?? '',
      netQty: (json['netQty'] ?? 0).toDouble(),
      netMs: (json['netMs'] ?? 0).toDouble(),
      carryFwdQty: (json['carryFwdQty'] ?? 0).toDouble(),
      carryFwdMs: (json['carryFwdMs'] ?? 0).toDouble(),
      openQty: (json['openQty'] ?? 0).toDouble(),
      openMs: (json['openMs'] ?? 0).toDouble(),
      totalQty: (json['totalQty'] ?? 0).toDouble(),
      totalMs: (json['totalMs'] ?? 0).toDouble(),
      buyQty: (json['buyQty'] ?? 0).toDouble(),
      buyMs: (json['buyMs'] ?? 0).toDouble(),
      sellQty: (json['sellQty'] ?? 0).toDouble(),
      sellMs: (json['sellMs'] ?? 0).toDouble(),
      netAvgPrice: (json['netAvgPrice'] ?? 0).toDouble(),
      cmp: (json['cmp'] ?? 0).toDouble(),
      m2m: (json['m2m'] ?? 0).toDouble(),
      releasePL: (json['releasePL'] ?? 0).toDouble(),
      netPL: (json['netPL'] ?? 0).toDouble(),
      brokerage: (json['brokerage'] ?? 0).toDouble(),
      netPLWithBrokerage: (json['netPLWithBrokerage'] ?? 0).toDouble(),
    );
  }
}
